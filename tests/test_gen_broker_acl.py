def _match(flt: str, topic: str) -> bool:
    f, t = flt.split("/"), topic.split("/")
    for i, part in enumerate(f):
        if part == "#":
            return True
        if i >= len(t) or (part != "+" and part != t[i]):
            return False
    return len(f) == len(t)


def _allowed(acl: str, user: str, access: str, topic: str) -> bool:
    """Mosquitto semantics: deny unless a rule for the user matches."""
    current = None
    for line in acl.splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[0] == "user":
            current = parts[1]
        elif (
            len(parts) == 3
            and parts[0] == "topic"
            and current == user
            and parts[1] == access
            and _match(parts[2], topic)
        ):
            return True
    return False


def test_golden_acl() -> None:
    assert gen.render_acl(["bot-b", "bot-a"]) == GOLDEN


def test_cross_device_isolation() -> None:
    acl = gen.render_acl(["bot-a", "bot-b"])
    for suffix in gen.DEVICE_PUBLISH:
        assert _allowed(acl, "bot-a", "write", f"thingwire/bot-a/{suffix}")
        assert not _allowed(acl, "bot-a", "write", f"thingwire/bot-b/{suffix}")
        assert not _allowed(acl, "bot-a", "read", f"thingwire/bot-b/{suffix}")
    assert _allowed(acl, "bot-a", "read", "thingwire/bot-a/command")
    assert not _allowed(acl, "bot-a", "read", "thingwire/bot-b/command")
    assert not _allowed(acl, "bot-a", "read", "thingwire/bot-b/estop")
    assert not _allowed(acl, "bot-a", "write", "thingwire/bot-a/command")
    assert not _allowed(acl, "bot-a", "write", "thingwire/estop")
    assert not _allowed(acl, "bot-a", "read", "thingwire/#")
    assert _allowed(acl, "bot-a", "read", "thingwire/estop")


def test_gateway_permissions() -> None:
    acl = gen.render_acl(["bot-a"])
    assert _allowed(acl, gen.GATEWAY_USER, "read", "thingwire/bot-a/telemetry")
    assert _allowed(acl, gen.GATEWAY_USER, "write", "thingwire/bot-a/command")
    assert _allowed(acl, gen.GATEWAY_USER, "write", "thingwire/estop")
    assert not _allowed(acl, gen.GATEWAY_USER, "write", "thingwire/bot-a/telemetry")
    assert not _allowed(acl, gen.GATEWAY_USER, "read", "thingwire/bot-a/command")
    assert not _allowed(acl, gen.GATEWAY_USER, "read", "other/topic")


@pytest.mark.parametrize(
    "bad", ["a+b", "a#", "a/b", "a b", "a\tb", "", "a\nb", "a:b", "+", "#", gen.GATEWAY_USER]
)
def test_injection_ids_rejected(bad: str) -> None:
    with pytest.raises(gen.InvalidDeviceIdError):
        gen.validate_device_id(bad)


def test_hash_round_trip() -> None:
    h = gen.hash_password("s3cret")
    parts = h.split("$")
    assert parts[:3] == ["", "7", "101"]
    assert len(__import__("base64").b64decode(parts[3])) == gen.SALT_BYTES
    assert len(__import__("base64").b64decode(parts[4])) == gen.HASH_BYTES
    assert gen.verify_password("s3cret", h)
    assert not gen.verify_password("wrong", h)
    assert gen.hash_password("s3cret") != h  # random salt


def test_known_vector() -> None:
    # Fixed salt gives a stable hash that verifies.
    h = gen.hash_password("pw", salt=b"0123456789ab")
    assert h == gen.hash_password("pw", salt=b"0123456789ab")
    assert gen.verify_password("pw", h)


def test_cli_writes_files_with_modes(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    out = tmp_path / "acl"
    assert gen.main(["--device", "bot-a", "--device", "bot-b", "--out", str(out)]) == 0
    creds = json.loads((out / "credentials.json").read_text())
    assert set(creds) == {gen.GATEWAY_USER, "bot-a", "bot-b"}
    assert stat.S_IMODE((out / "credentials.json").stat().st_mode) == 0o600
    for line in (out / "mosquitto.passwd").read_text().splitlines():
        user, enc = line.split(":", 1)
        assert gen.verify_password(creds[user], enc)
    printed = capsys.readouterr().out
    assert not any(pw in printed for pw in creds.values())


def test_cli_rejects_bad_id(tmp_path: Path) -> None:
    assert gen.main(["--device", "a/b", "--out", str(tmp_path / "o")]) == 2
    assert not (tmp_path / "o").exists()


def test_td_and_roster_sources(tmp_path: Path) -> None:
    td = tmp_path / "x.td.json"
    td.write_text(json.dumps({"id": "urn:thingwire:device:bot-z"}))
    tpl = tmp_path / "tpl.json"
    tpl.write_text(json.dumps({"id": "urn:thingwire:device:{device_id}"}))
    roster = tmp_path / "r.json"
    roster.write_text(json.dumps({"bot-r": {}}))
    assert gen.collect_ids([], [roster], [td, tpl]) == ["bot-r", "bot-z", "tpl"]
