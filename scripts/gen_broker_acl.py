#!/usr/bin/env python3
"""Generate per-device Mosquitto ACL and password files.

Each device may only publish its own td/telemetry/status/event/safety_status
topics and subscribe to its own command/estop topics plus the global estop.
The gateway user may read all device output topics and publish command/estop.
Everything else is denied (Mosquitto denies by default once an acl_file is set).

Usage:
    python scripts/gen_broker_acl.py --device desk-bot-1 --device bme-1
    python scripts/gen_broker_acl.py --roster data/roster.json --td td-library/x.json

Outputs (default dir docker/acl/, git-ignored):
    mosquitto.acl       ACL file
    mosquitto.passwd    password file, PBKDF2-SHA512 ($7$) hashes
    credentials.json    plaintext per-user passwords, mode 0600. Never commit.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import hmac
import json
import os
import re
import secrets
import sys
from pathlib import Path

GATEWAY_USER = "thingwire-gateway"
TOPIC_ROOT = "thingwire"
DEVICE_PUBLISH = ("td", "telemetry", "status", "event", "safety_status")
DEVICE_SUBSCRIBE = ("command", "estop")
GATEWAY_COMMAND = ("command", "estop")

PBKDF2_ITERATIONS = 101  # mosquitto_passwd $7$ default
SALT_BYTES = 12
HASH_BYTES = 64
PASSWORD_BYTES = 32

_VALID_ID = re.compile(r"^[A-Za-z0-9._-]{1,64}$")
_URN_PREFIX = "urn:thingwire:device:"


class InvalidDeviceIdError(ValueError):
    """Raised when a device id could widen an ACL or corrupt the files."""


def validate_device_id(device_id: str) -> str:
    """Reject ids that contain MQTT wildcards, separators, whitespace or other odd chars."""
    if not isinstance(device_id, str) or not _VALID_ID.fullmatch(device_id):
        raise InvalidDeviceIdError(
            f"invalid device id {device_id!r}: use 1-64 chars from A-Z a-z 0-9 . _ - "
            "(no '+', '#', '/', ':', whitespace)"
        )
    if device_id == GATEWAY_USER:
        raise InvalidDeviceIdError(f"device id {device_id!r} collides with the gateway user")
    return device_id


def hash_password(password: str, salt: bytes | None = None) -> str:
    """Return a mosquitto_passwd compatible `$7$` PBKDF2-HMAC-SHA512 hash."""
    salt = salt if salt is not None else secrets.token_bytes(SALT_BYTES)
    digest = hashlib.pbkdf2_hmac(
        "sha512", password.encode(), salt, PBKDF2_ITERATIONS, dklen=HASH_BYTES
    )
    return (
        f"$7${PBKDF2_ITERATIONS}${base64.b64encode(salt).decode()}"
        f"${base64.b64encode(digest).decode()}"
    )


def verify_password(password: str, encoded: str) -> bool:
    """Check a password against a `$7$` hash."""
    parts = encoded.split("$")
    if len(parts) != 5 or parts[0] != "" or parts[1] != "7":
        return False
    try:
        iterations = int(parts[2])
        salt = base64.b64decode(parts[3], validate=True)
        expected = base64.b64decode(parts[4], validate=True)
    except ValueError:
        return False
    actual = hashlib.pbkdf2_hmac("sha512", password.encode(), salt, iterations, dklen=len(expected))
    return hmac.compare_digest(actual, expected)


def render_acl(device_ids: list[str]) -> str:
    """Render the Mosquitto acl_file text for the given devices."""
    lines = ["# Generated by scripts/gen_broker_acl.py. Do not edit.", ""]
    lines += [f"user {GATEWAY_USER}"]
    lines += [f"topic read {TOPIC_ROOT}/+/{s}" for s in DEVICE_PUBLISH]
    lines += [f"topic write {TOPIC_ROOT}/+/{s}" for s in GATEWAY_COMMAND]
    lines += [f"topic write {TOPIC_ROOT}/estop", ""]
    for dev in sorted(device_ids):
        lines.append(f"user {dev}")
        lines += [f"topic write {TOPIC_ROOT}/{dev}/{s}" for s in DEVICE_PUBLISH]
        lines += [f"topic read {TOPIC_ROOT}/{dev}/{s}" for s in DEVICE_SUBSCRIBE]
        lines += [f"topic read {TOPIC_ROOT}/estop", ""]
    return "\n".join(lines)


def device_id_from_td(path: Path) -> str:
    """Take the id from a TD's urn suffix, falling back to the file stem."""
    stem = path.name.split(".")[0]
    try:
        raw = json.loads(path.read_text()).get("id", "")
    except (OSError, json.JSONDecodeError):
        raw = ""
    if isinstance(raw, str) and raw.startswith(_URN_PREFIX):
        suffix = raw[len(_URN_PREFIX) :]
        if suffix and not suffix.startswith("{"):
            return suffix
    return stem


def collect_ids(devices: list[str], rosters: list[Path], tds: list[Path]) -> list[str]:
    ids = list(devices)
    for roster in rosters:
        data = json.loads(roster.read_text())
        ids += list(data.keys()) if isinstance(data, dict) else list(data)
    ids += [device_id_from_td(p) for p in tds]
    unique = sorted(set(ids))
    for dev in unique:
        validate_device_id(dev)
    return unique


def generate(device_ids: list[str]) -> tuple[str, str, dict[str, str]]:
    """Return (acl_text, passwd_text, plaintext credentials)."""
    creds = {u: secrets.token_urlsafe(PASSWORD_BYTES) for u in [GATEWAY_USER, *device_ids]}
    passwd = "".join(f"{u}:{hash_password(p)}\n" for u, p in creds.items())
    return render_acl(device_ids), passwd, creds


def _write(path: Path, text: str, mode: int) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    with os.fdopen(fd, "w") as fh:
        fh.write(text)
    os.chmod(path, mode)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--device", action="append", default=[], help="device id (repeatable)")
    ap.add_argument("--roster", action="append", default=[], type=Path, help="roster JSON file")
    ap.add_argument("--td", action="append", default=[], type=Path, help="TD file (repeatable)")
    ap.add_argument("--out", type=Path, default=Path("docker/acl"), help="output directory")
    args = ap.parse_args(argv)

    try:
        ids = collect_ids(args.device, args.roster, args.td)
    except (InvalidDeviceIdError, OSError, json.JSONDecodeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if not ids:
        print("error: no devices given", file=sys.stderr)
        return 2

    acl, passwd, creds = generate(ids)
    args.out.mkdir(parents=True, exist_ok=True)
    # Hashes and ACL are readable by the broker's container user; plaintext is owner-only.
    _write(args.out / "mosquitto.acl", acl, 0o644)
    _write(args.out / "mosquitto.passwd", passwd, 0o644)
    _write(args.out / "credentials.json", json.dumps(creds, indent=2) + "\n", 0o600)
    print(f"wrote ACL and password files for {len(ids)} device(s) plus the gateway to {args.out}")
    print(f"plaintext passwords: {args.out / 'credentials.json'} (mode 0600, do not commit)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
